"""
Executive Tax Due Diligence Report Generator.
Generates comprehensive M&A Tax Diligence Memos in Markdown and HTML formats.
"""

from typing import Dict, Any
from core.models import AssessmentResult

class ReportGenerator:
    """Generates boardroom-quality Tax Due Diligence Memos for CAs and Investment Committees."""

    @staticmethod
    def generate_markdown_report(result: AssessmentResult) -> str:
        lit = result.litigation
        exp = result.exposure
        deal = result.deal_recommendation

        md = f"""# TAX DUE DILIGENCE REPORT: CONTINGENT LIABILITY ASSESSMENT
**Subject Entity:** {lit.company_name}  
**Assessment Year / Period:** {lit.assessment_year}  
**Tax Category:** {lit.tax_type} ({', '.join(lit.sections)})  
**Dispute Stage:** {lit.forum}  
**Jurisdiction:** {lit.jurisdiction_state}, India  
**Date of Assessment:** {lit.demand_notice_date}  

---

## 1. EXECUTIVE SUMMARY & IND AS 37 EVALUATION

| Evaluation Metric | Assessment Finding |
| :--- | :--- |
| **Materialization Probability** | **{result.crystallization_probability:.1f}%** |
| **Ind AS 37 / AS 29 Status** | **{result.ind_as_37_classification.value}** |
| **Disputed Base Demand** | **INR {exp.base_tax_demand:,.2f}** |
| **Accrued Interest to Date** | **INR {exp.interest_amount:,.2f}** |
| **Potential Penalty Exposure** | **INR {exp.penalty_recommended:,.2f}** |
| **Total Gross Exposure** | **INR {exp.total_gross_exposure:,.2f}** |
| **Pre-Deposit Already Paid** | **INR {exp.pre_deposit_paid:,.2f}** |
| **Net Unfunded Cash Risk** | **INR {exp.remaining_cash_at_risk:,.2f}** |

### M&A Negotiation & Deal Structuring Impact
> **Recommendation:** {deal.deal_negotiation_memo}

* **EV to Equity Net Debt Deduction:** INR {deal.net_debt_deduction_amount:,.2f}
* **Suggested Escrow Holdback / Bank Guarantee:** INR {deal.escrow_holdback_suggested:,.2f}
* **Specific Indemnity Required:** {"YES (Uncapped by de minimis / basket)" if deal.specific_indemnity_needed else "NO (Covered by standard warranties)"}

---

## 2. DISPUTE BACKGROUND & FACTUAL MATRIX
* **Core Issue:** {lit.dispute_type}
* **Current Status:** {lit.status}
* **Factual Summary:** {lit.facts_summary}

### Competing Positions
* **Tax Department's Contention:**
  > "{lit.department_arguments}"

* **Company's / Assessee's Contention:**
  > "{lit.company_arguments}"

---

## 3. JUDICIAL PRECEDENTS & CASE LAW ANALYSIS

The materialization risk has been evaluated against landmark Supreme Court and High Court authorities:

"""
        if not result.matching_precedents:
            md += "*No direct matching landmark precedents were retrieved from the benchmark repository.*\n\n"
        else:
            for idx, match in enumerate(result.matching_precedents, 1):
                p = match.precedent
                md += f"""### {idx}. {p.case_title}
* **Citation:** `{p.citation}`
* **Court & Authority:** {p.court} (**{match.binding_authority}**)
* **Subject Matter:** {p.subject}
* **Favorable To:** **{p.favorable_to}** (Relevance: {match.relevance_score * 100:.0f}%, Distinguishing Risk: {match.distinguishing_risk})
* **Ratio Decidendi:**  
  {p.ratio_decidendi}
* **Key Distinguishing Factors to Verify:**
"""
                for factor in p.key_distinguishing_factors:
                    md += f"  - {factor}\n"
                md += "\n"

        md += f"""---

## 4. FINANCIAL EXPOSURE & WATERFALL ANALYSIS

```text
[Base Demand]        INR {exp.base_tax_demand:>14,.2f}
  + [Accrued Interest] INR {exp.interest_amount:>14,.2f}
  + [Penalty Exposure] INR {exp.penalty_recommended:>14,.2f}
-------------------------------------------------------
= [Gross Exposure]   INR {exp.total_gross_exposure:>14,.2f}
  - [Pre-deposit]    INR {exp.pre_deposit_paid:>14,.2f}
-------------------------------------------------------
= [Net Cash at Risk] INR {exp.remaining_cash_at_risk:>14,.2f}
```

### Interest Breakdown
"""
        for item, amt in exp.interest_breakdown.items():
            md += f"- **{item}:** INR {amt:,.2f}\n"

        md += f"""
### Appeal Stay / Pre-Deposit Obligation
Under statutory requirements, maintaining stay on recovery requires an estimated deposit of **INR {exp.appeal_stay_deposit_needed:,.2f}**.

---

## 5. RISK DRIVERS & MITIGATING FACTORS

### Key Risk Drivers (Aggravating Factors)
"""
        for r in result.key_risk_drivers:
            md += f"- ⚠️ {r}\n"

        md += "\n### Mitigating Factors (Defenses Available)\n"
        for m in result.mitigating_factors:
            md += f"- ✅ {m}\n"

        md += """
---
*Report generated by Antigravity Tax Due Diligence Engine for Chartered Accountants.*  
*Note: This report provides analytical and legal precedent probability evaluation and should be reviewed by legal counsel.*
"""
        return md

